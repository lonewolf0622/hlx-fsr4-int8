"""glsl2hlsl.py IN.comp OUT.hlsl: one of HLX FSR 4 Full's generated network kernels (gen_cnx2f / gen_ds / gen_fnb5 / gen_c64c:
buffer bindings only) as HLSL for DXIL, the D3D12 path (Windows). Bindings as the D3D12 kernel backend (hlx_fsr4.c dxk_*) sets
them: push constants -> root constants b1, binding 0 (In, the scratch) -> root UAV u0, binding 1 (Wt, the weights, <= 64 KiB)
-> root CBV b0, binding 2 (Out, the scratch) -> root UAV u1, binding 3 (the weights as a storage buffer) -> root SRV t0.
The body stays GLSL; a small header maps the rest (types, constructors, built-ins). Loops marked dont_unroll get a runtime zero
in their bound (DXIL does not carry the hint; unrolled, a kernel needs far more registers)."""
import re, sys

HEADER = r'''// generated by glsl2hlsl.py from the GLSL kernel (HLX FSR 4 Full, D3D12 path)
typedef vector<float16_t, 2> f16vec2;
typedef vector<float16_t, 4> f16vec4;
typedef float2 vec2;
typedef float4 vec4;
typedef uint2 uvec2;
typedef uint4 uvec4;
typedef int2 ivec2;
vector<float16_t, 2> pw_f16vec2(float a) { return vector<float16_t, 2>((float16_t)a, (float16_t)a); }
vector<float16_t, 2> pw_f16vec2(float a, float b) { return vector<float16_t, 2>((float16_t)a, (float16_t)b); }
vector<float16_t, 2> pw_f16vec2(float2 v) { return (vector<float16_t, 2>)v; }
vector<float16_t, 2> pw_f16vec2(vector<float16_t, 2> v) { return v; }
#define f16vec2(...) pw_f16vec2(__VA_ARGS__)
float2 pw_vec2(float a) { return float2(a, a); }
float2 pw_vec2(float a, float b) { return float2(a, b); }
float2 pw_vec2(vector<float16_t, 2> v) { return (float2)v; }
float2 pw_vec2(float2 v) { return v; }
#define vec2(...) pw_vec2(__VA_ARGS__)
uint packFloat2x16(vector<float16_t, 2> v) { return uint(asuint16(v.x)) | (uint(asuint16(v.y)) << 16); }
vector<float16_t, 2> unpackFloat2x16(uint u) { return vector<float16_t, 2>(asfloat16(uint16_t(u)), asfloat16(uint16_t(u >> 16))); }
uint packHalf2x16(float2 v) { return f32tof16(v.x) | (f32tof16(v.y) << 16); }
float2 unpackHalf2x16(uint u) { return float2(f16tof32(u), f16tof32(u >> 16)); }
#define uintBitsToFloat asfloat
#define floatBitsToUint asuint
#define uint16BitsToFloat16 asfloat16
#define float16BitsToUint16 asuint16
#define roundEven round
#define fma mad
#define fract frac
#define mix lerp
#define inversesqrt rsqrt
#define shared groupshared
void barrier() { GroupMemoryBarrierWithGroupSync(); }
#define gl_LocalInvocationID pw_lid3
#define gl_LocalInvocationIndex pw_lidx
#define gl_WorkGroupID pw_gid3
#define gl_GlobalInvocationID pw_did3
#define gl_SubgroupSize WaveGetLaneCount()
#define gl_SubgroupInvocationID WaveGetLaneIndex()
int dotPacked4x8EXT(int a, int b) { return dot4add_i8packed(uint(a), uint(b), 0); }   // (int8 kernels: signed 4 x int8 dot)
#define gl_SubgroupID WaveReadLaneFirst(pw_lidx / WaveGetLaneCount())   // (provably wave-uniform: scalar weight loads)
'''


def main():
    src, dst = sys.argv[1:3]
    s = open(src).read()
    out = []
    local = None
    for line in s.splitlines():
        t = line.strip()
        if t.startswith('#version') or t.startswith('#extension'):
            continue
        m = re.match(r'layout\(local_size_x\s*=\s*(\d+)\)\s*in;', t)
        if m:
            local = int(m.group(1)); continue
        m = re.match(r'layout\(set\s*=\s*0,\s*binding\s*=\s*(\d+)(?:,\s*std140)?\)\s*(readonly |writeonly )?(buffer|uniform)\s+\w+\s*\{\s*(\w+)\s+(\w+)\[(\d*)\];\s*\};', t)
        if m:
            b, kind, typ, name, n = int(m.group(1)), m.group(3), m.group(4), m.group(5), m.group(6)
            htyp = {'uint': 'uint', 'uvec4': 'uint4', 'uvec2': 'uint2'}[typ]
            if b == 0: out.append(f'RWStructuredBuffer<{htyp}> {name} : register(u0);')
            elif b == 1 and kind == 'uniform': out.append(f'cbuffer Wt : register(b0) {{ {htyp} {name}[{n}]; }};')
            elif b == 2: out.append(f'RWStructuredBuffer<{htyp}> {name} : register(u1);')
            elif b == 3: out.append(f'StructuredBuffer<{htyp}> {name} : register(t0);')
            else: raise SystemExit(f'{src}: binding {b} not handled: {t}')
            continue
        m = re.match(r'layout\(push_constant\)\s*uniform\s+\w+\s*\{\s*(.*);\s*\};', t)
        if m:
            out.append(f'cbuffer Pc : register(b1) {{ {m.group(1)}; uint pw_rt0; }};   // (pw_rt0: zero, past the pushed values)')
            continue
        if t.startswith('layout('):
            raise SystemExit(f'{src}: layout not handled: {t}')
        out.append(line)
    if not local:
        raise SystemExit(f'{src}: no local size')
    body = '\n'.join(out)
    body = body.replace('[[unroll]]', '[unroll]')
    # [unroll] needs a count DXC can deduce: loops that start at a runtime value (the tile loader: e = l) get none
    body = re.sub(r'\[unroll\](\s*for \((?:uint|int) \w+ = )([^;]+);', lambda m: (m.group(0) if re.fullmatch(r'\s*\d+u?\s*', m.group(2)) else m.group(1).lstrip() + m.group(2) + ';'), body)
    n0 = body.count('[[dont_unroll]]')
    body = re.sub(r'\[\[dont_unroll\]\](\s*)for \(([^;]*);\s*(\w+)\s*<\s*([^;]+);', lambda m: f'[loop]{m.group(1)}for ({m.group(2)}; {m.group(3)} < ({m.group(4).strip()}) + pw_rt0;', body)
    if '[[dont_unroll]]' in body:
        raise SystemExit(f'{src}: dont_unroll loop not converted')
    body = re.sub(r'\bvoid main\(\)', f'[WaveSize(32)] [numthreads({local}, 1, 1)] void main(uint3 pw_lid3 : SV_GroupThreadID, uint pw_lidx : SV_GroupIndex, uint3 pw_gid3 : SV_GroupID, uint3 pw_did3 : SV_DispatchThreadID)', body)
    open(dst, 'w').write(HEADER + body + '\n')
    print(f'{dst}: local {local}, {n0} loops kept')


if __name__ == '__main__':
    main()
